<div class="box tip"><span class="t">На пальцах</span>Крамер похож на поиск доли через определители. Ты считаешь главный определитель всей системы, а потом заменяешь один столбец на ответы и снова считаешь определитель. Делишь одно на другое — получаешь икс или игрек. Это удобно, если нужно найти только одну переменную, но для больших систем это слишком долго.</div>

