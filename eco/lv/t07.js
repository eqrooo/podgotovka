<p>Кислотность измеряют по шкале <b>pH</b> (водородный показатель). Чистая вода имеет pH 7 и считается нейтральной. Чем меньше число, тем кислее среда. Обычный дождь всё же слабокислый: pH около 5–5,6. Почему? В воздухе есть углекислый газ. Он растворяется в капельках и образует слабую угольную кислоту.</p>
