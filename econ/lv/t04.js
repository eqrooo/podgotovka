<p>Представь, что ты фермер и хочешь купить сапоги. У тебя есть мешок картофеля, а у сапожника нет картофеля, зато нужна мука. Обмен прямо «товар на товар» называется <b>бартером</b>. Он очень неудобен: нужно найти человека, которому нужен твой товар и у которого есть нужный тебе. Это называют «двойным совпадением потребностей».</p>
