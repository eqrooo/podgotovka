<p>The word "sociology" is made of two parts. The first comes from the Latin <i>socius</i>, meaning "companion" or "comrade". The second comes from the Greek <i>logos</i>, meaning "study" or "teaching". Together they mean "the science of society and human communication". Sociology studies how people live together, how they behave, how they interact and what relationships form between them.</p>
