<h3>Матрицы и размеры</h3>
<ul>
<li><b>Матрица</b> — прямоугольная таблица чисел \(A_{n\times m}=[a_{ij}]\) из \(n\) строк и \(m\) столбцов.</li>
<li>Элемент \(a_{ij}\) стоит в строке \(i\) и столбце \(j\).</li>
