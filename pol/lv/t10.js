<div class="box warn"><span class="t">Частая ошибка</span>Путать эмиграцию с иммиграцией. Для одного и того же человека это одно и то же перемещение. Со стороны страны отправления оно называется эмиграцией, а со стороны страны назначения — иммиграцией.</div>

