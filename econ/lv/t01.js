<p>Блага делятся на свободные и экономические. Воздух обычно свободный, его не нужно покупать. Экономические блага ограничены: чтобы их получить, нужны ресурсы. Самый наглядный ограниченный ресурс — время. В сутках 24 часа, и студент делит их между учёбой, работой и отдыхом.</p>

